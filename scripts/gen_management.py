def _classify() -> tuple[set[str], set[str]]:
    """Split the spec's schemas into (enums, discriminated unions), by RENDERED name.

    Computed once, up front, because the alternative -- asking "is this an enum?" from
    inside an emitter by re-looking-up a name -- is what shipped the first round of this
    port with `NotificationEventType::fromArray()` on a backed enum and
    `ProviderConfig` declared where a `ProviderConfigVariant` is returned. A name is not
    enough to know a schema's KIND; this table is.
    """
    enums: set[str] = set()
    unions: set[str] = set()
    for name, schema in SCHEMAS.items():
        if not isinstance(schema, dict):
            continue
        if isinstance(schema.get("enum"), list):
            enums.add(pascal(name))
        elif discriminated(schema):
            unions.add(pascal(name))
    return enums, unions


ENUMS, UNIONS = _classify()


def type_name(name: str) -> str:
    """The PHP type a `$ref` to ``name`` denotes.

    A union's decoder returns the INTERFACE its arms implement, not the dispatcher class
    that picks between them, so the two names differ and only one of them is a valid
    type declaration.
    """
    rendered = pascal(name)
    return f"{rendered}Variant" if rendered in UNIONS else rendered


def php_type(schema: Any, secret: bool = False) -> tuple[str, str]:
    """Map an ``openapi.json`` schema to ``(declared type, docblock type)``.

    Two types rather than one because PHP's type declarations cannot express what
    PHPStan level 6 requires: ``array`` is a legal declaration but an unusable one, so
    every array carries a ``list<T>``/``array<string,mixed>`` docblock beside it. Where
    the two agree the caller simply emits the declaration.
    """
    if secret:
        return (SENSITIVE, SENSITIVE)

    if not isinstance(schema, dict):
        return ("mixed", "mixed")

    if "$ref" in schema:
        name = type_name(schema["$ref"].split("/")[-1])
        return (name, name)

    inner = nullable_ref(schema)
    if inner:
        name = type_name(inner)
        return (f"?{name}", f"{name}|null")

    if isinstance(schema.get("allOf"), list) and len(schema["allOf"]) == 1:
        return php_type(schema["allOf"][0])

    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)

    if kind == "array":
        item_decl, item_doc = php_type(schema.get("items") or {})
        return ("array", f"list<{item_doc.lstrip('?')}>")
    if kind == "integer":
        return ("int", "int")
    if kind == "number":
        return ("float", "float")
    if kind == "boolean":
        return ("bool", "bool")
    if kind == "string":
        return ("string", "string")
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        return ("array", "array<string,mixed>")

    return ("mixed", "mixed")


def nullable(decl: str) -> str:
    """``decl`` made nullable, respecting the two types that refuse the ``?`` prefix.

    ``?mixed`` is a fatal error -- ``mixed`` already includes null -- and re-prefixing an
    already-nullable ``?T`` is one too.
    """
    if decl == "mixed" or decl.startswith("?"):
        return decl
    return f"?{decl}"


def enum_case(value: str) -> str:
    """A PHP enum case name for a wire value (``pending_review`` -> ``PendingReview``)."""
    name = pascal(value)
    if not name or not name[0].isalpha():
        name = f"Value{name}"
    return name


def header(namespace: str, uses: list[str] | None = None) -> str:
    """The file preamble: banner, namespace, and sorted ``use`` statements."""
    out = BANNER + f"\nnamespace {namespace};\n"
    unique = sorted(set(uses or []))
    if unique:
        out += "\n" + "".join(f"use {u};\n" for u in unique)
    return out


def replacement_schemas() -> set[str]:
    """Request schemas the registry marks as full replacements, not sparse updates.

    §27.4 rule 5 makes the difference load-bearing: a replacement body requires every
    field, so omitting one is a constructor error you cannot ship, while a sparse body
    omits what you did not name.
    """
    out: set[str] = set()
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"] and op.get("update_style") == "replace":
                out.add(op["request_schema"].lstrip("[]"))
    return out


def field_list(schema_name: str, secrets: set[str]) -> tuple[list[dict[str, Any]], str | None]:
    """Every field of ``schema_name``, required first (PHP ordering), plus its description."""
    props, required, description = flatten(schema_name)
    fields: list[dict[str, Any]] = []
    for wire, schema in props.items():
        decl, doc = php_type(schema, secret=wire in secrets)
        is_required = wire in required
        fields.append({
            "wire": wire,
            "name": prop(wire),
            "decl": decl,
            "doc": doc,
            "required": is_required,
            "schema": schema,
            "secret": wire in secrets,
            "description": schema.get("description") if isinstance(schema, dict) else None,
        })
    # PHP forbids a required parameter after an optional one, so required fields must
    # be emitted first. Within each group the spec's own order is preserved so the
    # generated class still reads like the schema it came from.
    return ([f for f in fields if f["required"]] + [f for f in fields if not f["required"]],
            description)


def field_doc(field: dict[str, Any]) -> str:
    """The one-line description for a field, falling back to naming the wire key."""
    if field["description"]:
        return escape(field["description"])
    if field["secret"]:
        return f"the server's `{field['wire']}` field — a one-time secret (§27.5)"
    return f"the server's `{field['wire']}` field"


def decode_one(type_decl: str, source: str) -> str:
    """PHP that turns one raw wire value of declared type ``type_decl`` into that type."""
    if type_decl in {"int", "float", "string", "bool"}:
        return f"({type_decl}) {source}"
    if type_decl == "mixed":
        return source
    if type_decl in ENUMS:
        return f"{type_decl}::fromWire((string) {source})"
    if type_decl.endswith("Variant") and type_decl[:-len("Variant")] in UNIONS:
        # The dispatcher picks the arm; the interface is what the arm satisfies.
        return f"{type_decl[:-len('Variant')]}::fromArray((array) {source})"
    return f"{type_decl}::fromArray((array) {source})"


def decode_expr(field: dict[str, Any], source: str) -> str:
    """PHP source that turns one raw wire value into the field's declared type."""
    decl = field["decl"].lstrip("?")
    doc = field["doc"]

    if field["secret"]:
        return f"new \\Axiam\\Sdk\\Core\\Sensitive((string) {source})"
    if decl == "array" and doc.startswith("list<"):
        item = doc[5:-1]
        if item == "mixed" or item.startswith("array<"):
            return f"array_values((array) {source})"
        return (f"array_values(array_map(static fn (mixed $v): {item} => "
                f"{decode_one(item, '$v')}, (array) {source}))")
    if decl == "array":
        return f"(array) {source}"
    return decode_one(decl, source)


def encode_one(type_decl: str, ref: str) -> str:
    """PHP that turns one value of declared type ``type_decl`` back into its wire form.

    Always ``->``, never ``?->``: an optional field is only ever encoded INSIDE its own
    ``!== null`` guard, so the nullsafe operator would be dead syntax -- and PHPStan says
    so at level 6 rather than letting it sit there implying a null that cannot occur.
    """
    if type_decl in {"int", "float", "string", "bool", "mixed"}:
        return ref
    if type_decl in ENUMS:
        return f"{ref}->value"
    return f"{ref}->toArray()"


def encode_expr(field: dict[str, Any]) -> str:
    """PHP source that turns one field back into its wire value."""
    decl = field["decl"].lstrip("?")
    doc = field["doc"]
    ref = f"$this->{field['name']}"

    if field["secret"]:
        # Left wrapped on purpose: ManagementTransport::encodeBody() is the ONLY place a
        # Sensitive is revealed, so a body rendered anywhere else stays redacted.
        return ref
    if decl == "array" and doc.startswith("list<"):
        item = doc[5:-1]
        if item in {"int", "float", "string", "bool", "mixed"} or item.startswith("array<"):
            return ref
        inner = encode_one(item, "$v")
        cast = "string" if item in ENUMS else "array"
        return f"array_map(static fn ({item} $v): {cast} => {inner}, {ref})"
    if decl == "array":
        return ref
    return encode_one(decl, ref)



def emit_enum(name: str, schema: Any) -> str:
    """A backed enum whose case values are the wire spellings.

    ``fromWire()`` rather than the built-in ``from()`` because an unknown value must
    fail as an SDK error a caller can catch, not a bare ``\\ValueError``. It throws
    rather than falling back to a default case: on this surface these values gate
    access, and silently reading an unrecognised ``"suspended"`` as whichever case
    happens to be declared first turns a new server state into a wrong one.
    """
    values = [str(v) for v in schema.get("enum") or []]
    description = schema.get("description") or f"The `{name}` enumeration from the server's OpenAPI document."

    out = [header(MODELS_NS)]
    out.extend(docblock(escape(description)))
    out.append(f"enum {name}: string")
    out.append("{")
    for value in values:
        out.extend(inline_doc(f"The wire value `{escape(value)}`.", "    "))
        out.append(f"    case {enum_case(value)} = '{value}';")
        out.append("")
    out.extend(docblock(
        f"Parses a wire value into a {name}.\n\n"
        "Throws on an unrecognised value rather than defaulting to a case: a server "
        "that has learned a new state should surface as a loud error, not as whichever "
        "case was declared first.",
        "    ",
        ["@throws \\Axiam\\Sdk\\Core\\AxiamException when `$value` is not a known case."],
    ))
    out.append("    public static function fromWire(string $value): self")
    out.append("    {")
    out.append("        return self::tryFrom($value) ?? throw new \\Axiam\\Sdk\\Core\\AxiamException(")
    out.append(f"            sprintf('unknown {name} value \"%s\" — the server may be newer than this SDK', $value),")
    out.append("        );")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_class(name: str, secrets: set[str], replacement: bool) -> str:
    """A model class: promoted readonly properties, plus ``fromArray``/``toArray``.

    §27.4 rule 5 lives in the shape of the constructor. A SPARSE body's optional
    properties default to ``null`` and ``toArray()`` omits them, so an unset field is
    ABSENT from the wire request rather than sent as null. A REPLACEMENT body declares
    every field required, so omitting one is a ``TypeError`` at construction — the
    earliest a language can report it.
    """
    fields, description = field_list(name, secrets)
    sparse = not replacement and all(not f["required"] for f in fields) and bool(fields)

    summary = escape(description) if description else \
        f"The `{name}` schema from the server's OpenAPI document."
    if sparse:
        summary += (
            "\n\nEvery property is optional, so this is a SPARSE body: what you leave unset "
            "is left unchanged, and is omitted from the wire request entirely rather than "
            "sent as null (§27.4 rule 5)."
        )
    elif replacement:
        summary += (
            "\n\nThis is a REPLACEMENT body (§27.4 rule 5): every field is required, so "
            "omitting one is a constructor error rather than a silent erasure server-side."
        )

    uses = []
    out = [header(MODELS_NS, uses)]
    out.extend(docblock(summary))
    out.append(f"final class {name} implements \\JsonSerializable")
    out.append("{")

    # --- constructor ---
    tags = []
    for f in fields:
        optional = "" if f["required"] else " (optional)"
        suffix = "" if f["required"] or f["doc"] == "mixed" or f["doc"].endswith("|null") else "|null"
        tags.append(f"@param {f['doc']}{suffix} ${f['name']} {field_doc(f)}{optional}")
    out.extend(docblock(f"Constructs a {name}.", "    ", tags) if fields
               else docblock(f"Constructs a {name}. The schema declares no fields.", "    "))
    if not fields:
        out.append("    public function __construct()")
        out.append("    {")
        out.append("    }")
    else:
        out.append("    public function __construct(")
        for f in fields:
            decl = f["decl"] if f["required"] else nullable(f["decl"])
            default = "" if f["required"] else " = null"
            out.append(f"        public readonly {decl} ${f['name']}{default},")
        out.append("    ) {")
        out.append("    }")
    out.append("")

    # --- fromArray ---
    out.extend(docblock(
        f"Rebuilds a {name} from one decoded JSON object.",
        "    ",
        ["@param array<string,mixed> $data The raw wire object."],
    ))
    out.append("    public static function fromArray(array $data): self")
    out.append("    {")
    if not fields:
        out.append("        return new self();")
    else:
        out.append("        return new self(")
        for f in fields:
            src = f"$data['{f['wire']}']"
            if f["required"]:
                need = f"ModelDecode::need($data, '{f['wire']}', self::class)"
                out.append(f"            {decode_expr(f, need)},")
            else:
                out.append(f"            isset({src}) ? {decode_expr(f, src)} : null,")
        out.append("        );")
    out.append("    }")
    out.append("")

    # --- toArray ---
    out.extend(docblock(
        "Renders this object back to its wire form.\n\n"
        "§27.4 rule 5: a null property is OMITTED, not emitted as null. On a sparse "
        "update those two say opposite things — \"leave this alone\" versus \"set this to "
        "nothing\" — and only omission means the first.",
        "    ",
        ["@return array<string,mixed>"],
    ))
    out.append("    public function toArray(): array")
    out.append("    {")
    if not fields:
        out.append("        return [];")
    else:
        out.append("        $out = [];")
        for f in fields:
            expr = encode_expr(f)
            if f["required"]:
                out.append(f"        $out['{f['wire']}'] = {expr};")
            else:
                out.append(f"        if ($this->{f['name']} !== null) {{")
                out.append(f"            $out['{f['wire']}'] = {expr};")
                out.append("        }")
        out.append("")
        out.append("        return $out;")
    out.append("    }")
    out.append("")

    # --- jsonSerialize ---
    out.extend(docblock(
        "Renders this object for `json_encode()`.\n\n"
        "Any {@see " + SENSITIVE + "} it carries stays WRAPPED here, so a log line or a "
        "`json_encode($model)` in application code prints `[SENSITIVE]`. The one place a "
        "secret is revealed is {@see \\Axiam\\Sdk\\Management\\ManagementTransport}, on the "
        "way to the wire and nowhere else (§27.5).",
        "    ",
        ["@return array<string,mixed>"],
    ))
    out.append("    public function jsonSerialize(): array")
    out.append("    {")
    out.append("        return $this->toArray();")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_union(name: str, schema: Any, tag: str, arms: list[tuple[str, Any]]) -> dict[str, str]:
    """An internally-tagged union: one interface plus one class per arm.

    PHP has no sealed hierarchy, so the base is an interface and `fromArray` on a small
    dispatcher class picks the arm by its tag value. An unknown tag throws for the same
    reason an unknown enum value does.
    """
    files: dict[str, str] = {}
    description = schema.get("description") or f"The `{name}` union from the server's OpenAPI document."

    iface = [header(MODELS_NS)]
    iface.extend(docblock(
        escape(description) + f"\n\nDiscriminated on the wire by `{tag}`. Use "
        f"{{@see {name}::fromArray()}} to decode one; each arm is a separate class "
        "implementing this interface.",
    ))
    iface.append(f"interface {name}Variant extends \\JsonSerializable")
    iface.append("{")
    iface.extend(docblock(
        "Renders this variant to its wire form, including its discriminator.",
        "    ",
        ["@return array<string,mixed>"],
    ))
    iface.append("    public function toArray(): array;")
    iface.append("}")
    files[f"{MODELS_DIR}/{name}Variant.php"] = "\n".join(iface) + "\n"

    dispatch = [header(MODELS_NS)]
    dispatch.extend(docblock(
        escape(description) + f"\n\nThe decoder for the `{tag}`-tagged union. Every arm is a "
        f"{name}Variant; this class exists only to pick the right one.",
    ))
    dispatch.append(f"final class {name}")
    dispatch.append("{")
    dispatch.extend(docblock(
        f"Decodes one `{tag}`-tagged {name} object into its variant.",
        "    ",
        [
            "@param array<string,mixed> $data The raw wire object.",
            f"@throws \\Axiam\\Sdk\\Core\\AxiamException when `{tag}` is missing or unknown.",
        ],
    ))
    dispatch.append(f"    public static function fromArray(array $data): {name}Variant")
    dispatch.append("    {")
    dispatch.append(f"        $tag = $data['{tag}'] ?? null;")
    dispatch.append("")
    dispatch.append("        return match ($tag) {")
    for value, payload in arms:
        arm = f"{name}{pascal(value)}"
        dispatch.append(f"            '{value}' => {arm}::fromArray($data),")
    dispatch.append("            default => throw new \\Axiam\\Sdk\\Core\\AxiamException(")
    dispatch.append(f"                sprintf('unknown {name} {tag} \"%s\"', is_string($tag) ? $tag : gettype($tag)),")
    dispatch.append("            ),")
    dispatch.append("        };")
    dispatch.append("    }")
    dispatch.append("}")
    files[f"{MODELS_DIR}/{name}.php"] = "\n".join(dispatch) + "\n"

    for value, payload in arms:
        arm = f"{name}{pascal(value)}"
        resolved = resolve_ref(payload) if "$ref" in payload else payload
        props = resolved.get("properties") or {}
        required = set(resolved.get("required") or [])
        fields = []
        for wire, pschema in props.items():
            decl, doc = php_type(pschema)
            fields.append({
                "wire": wire, "name": prop(wire), "decl": decl, "doc": doc,
                "required": wire in required, "schema": pschema, "secret": False,
                "description": pschema.get("description") if isinstance(pschema, dict) else None,
            })
        fields = [f for f in fields if f["required"]] + [f for f in fields if not f["required"]]

        body = [header(MODELS_NS)]
        body.extend(docblock(
            f"The `{escape(value)}` arm of {{@see {name}}} (`{tag}: \"{escape(value)}\"`).",
        ))
        body.append(f"final class {arm} implements {name}Variant")
        body.append("{")
        tags = [
            "@param {}{} ${} {}".format(
                f["doc"],
                "" if f["required"] or f["doc"] == "mixed" or f["doc"].endswith("|null") else "|null",
                f["name"],
                field_doc(f),
            )
            for f in fields
        ]
        body.extend(docblock(f"Constructs the `{escape(value)}` arm.", "    ", tags) if fields
                    else docblock(f"Constructs the `{escape(value)}` arm, which carries no fields.", "    "))
        if not fields:
            body.append("    public function __construct()")
            body.append("    {")
            body.append("    }")
        else:
            body.append("    public function __construct(")
            for f in fields:
                decl = f["decl"] if f["required"] else nullable(f["decl"])
                default = "" if f["required"] else " = null"
                body.append(f"        public readonly {decl} ${f['name']}{default},")
            body.append("    ) {")
            body.append("    }")
        body.append("")
        body.extend(docblock(
            f"Rebuilds the `{escape(value)}` arm from one decoded JSON object.",
            "    ",
            ["@param array<string,mixed> $data The raw wire object."],
        ))
        body.append("    public static function fromArray(array $data): self")
        body.append("    {")
        if not fields:
            body.append("        return new self();")
        else:
            body.append("        return new self(")
            for f in fields:
                src = f"$data['{f['wire']}']"
                need = f"ModelDecode::need($data, '{f['wire']}', self::class)"
                body.append(f"            {decode_expr(f, need)}," if f["required"]
                            else f"            isset({src}) ? {decode_expr(f, src)} : null,")
            body.append("        );")
        body.append("    }")
        body.append("")
        body.extend(docblock(
            f"Renders this arm to its wire form, re-attaching `{tag}: \"{escape(value)}\"`.",
            "    ",
            ["@return array<string,mixed>"],
        ))
        body.append("    public function toArray(): array")
        body.append("    {")
        body.append(f"        $out = ['{tag}' => '{value}'];")
        for f in fields:
            expr = encode_expr(f)
            if f["required"]:
                body.append(f"        $out['{f['wire']}'] = {expr};")
            else:
                body.append(f"        if ($this->{f['name']} !== null) {{")
                body.append(f"            $out['{f['wire']}'] = {expr};")
                body.append("        }")
        body.append("")
        body.append("        return $out;")
        body.append("    }")
        body.append("")
        body.extend(docblock(
            "Renders this arm for `json_encode()`.",
            "    ",
            ["@return array<string,mixed>"],
        ))
        body.append("    public function jsonSerialize(): array")
        body.append("    {")
        body.append("        return $this->toArray();")
        body.append("    }")
        body.append("}")
        files[f"{MODELS_DIR}/{arm}.php"] = "\n".join(body) + "\n"

    return files


def emit_models() -> dict[str, str]:
    """Every model file, keyed by repo-relative path."""
    secrets = sensitive_map()
    replacements = replacement_schemas()
    files: dict[str, str] = {}
    for name in schema_closure():
        schema = SCHEMAS.get(name) or {}
        rendered = pascal(name)
        if isinstance(schema.get("enum"), list):
            files[f"{MODELS_DIR}/{rendered}.php"] = emit_enum(rendered, schema)
            continue
        union = discriminated(schema)
        if union:
            files.update(emit_union(rendered, schema, union[0], union[1]))
            continue
        files[f"{MODELS_DIR}/{rendered}.php"] = emit_class(
            rendered, secrets.get(name, set()), name in replacements)
    return files


