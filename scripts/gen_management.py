def path_param_names(op: dict[str, Any]) -> list[str]:
    """The `{placeholder}` names in an operation's path, in order."""
    return re.findall(r"\{([^}]+)\}", op["path"])


def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which path params the handle fills in itself (§27.4 rule 3).

    `{org_id}` is always the client's. `{tenant_id}` is the client's only where it names
    the CONTEXT of the call; in `tenants` and the signing-CA routes it names the object
    being administered, and taking it implicitly there would make it impossible to
    address any tenant but your own.
    """
    names = set(path_param_names(op))
    implicit = {"org_id"} & names
    if "tenant_id" in names and namespace in IMPLICIT_TENANT_NAMESPACES:
        implicit.add("tenant_id")
    return implicit


def split_query(op: dict[str, Any]) -> tuple[list[str], list[str]]:
    """Query parameters split into (required, optional), paging excluded."""
    required, optional = [], []
    for q in op["query_params"]:
        if op["paginated"] and q["name"] in {"offset", "limit"}:
            continue
        (required if q["required"] else optional).append(q["name"])
    return required, optional


def query_type(op: dict[str, Any], name: str) -> str:
    """The PHP type for one query parameter."""
    for q in op["query_params"]:
        if q["name"] != name:
            continue
        # The registry copies the spec's `type`, which for an optional parameter is a
        # LIST (`["string", "null"]`) rather than a bare string.
        kind = q["type"]
        if isinstance(kind, list):
            kind = next((k for k in kind if k != "null"), "string")
        return {"integer": "int", "number": "float", "boolean": "bool"}.get(kind, "string")
    return "string"


def operation_params(namespace: str, op: dict[str, Any]) -> list[dict[str, str]]:
    """The generated method's parameter list, required before optional."""
    implicit = implicit_params(namespace, op)
    params: list[dict[str, str]] = []

    for name in path_param_names(op):
        if name in implicit:
            continue
        params.append({
            "name": camel(name), "decl": "string", "doc": "string",
            "kind": "path", "wire": name, "required": "1",
            "text": f"the `{{{name}}}` path parameter",
        })

    required_q, optional_q = split_query(op)
    for name in required_q:
        t = query_type(op, name)
        params.append({
            "name": camel(name), "decl": t, "doc": t, "kind": "query", "wire": name,
            "required": "1", "text": f"the required `{name}` query parameter",
        })

    if op["request_body"] != "none" and op["request_schema"]:
        model = pascal(op["request_schema"].lstrip("[]"))
        params.append({
            "name": "body", "decl": model, "doc": model, "kind": "body", "wire": "",
            "required": "1", "text": "the request body",
        })

    if op["paginated"]:
        params.append({
            "name": "page", "decl": "?PageRequest", "doc": "PageRequest|null",
            "kind": "page", "wire": "", "required": "",
            "text": "which page to fetch; defaults to the first",
        })

    for name in optional_q:
        t = query_type(op, name)
        params.append({
            "name": camel(name), "decl": f"?{t}", "doc": f"{t}|null", "kind": "query",
            "wire": name, "required": "", "text": f"the optional `{name}` query parameter",
        })

    return params


def response_php(op: dict[str, Any]) -> tuple[str, str]:
    """The method's ``(declared return type, docblock return type)``."""
    kind = op["response"]["kind"]
    schema = op["response"]["schema"]
    if kind == "none" or not schema:
        return ("void", "void")
    model = type_name(schema.lstrip("[]"))
    if kind == "page":
        return ("Page", f"Page<{model}>")
    if kind == "array":
        return ("array", f"list<{model}>")
    return (model, model)


def spec_description(op: dict[str, Any]) -> str | None:
    """The `summary`/`description` ``openapi.json`` gives this path+method, if any."""
    entry = (SPEC.get("paths") or {}).get(op["path"]) or {}
    node = entry.get(op["method"].lower()) or {}
    text = node.get("summary") or node.get("description")
    return escape(text) if text else None


def operation_doc(op: dict[str, Any], name: str) -> str:
    """The docblock summary for one generated operation."""
    described = spec_description(op)
    lead = described or f"`{op['method']} {op['path']}`."
    if described:
        lead = f"{described}\n\n`{op['method']} {op['path']}`."

    kind = op["response"]["kind"]
    if kind == "page":
        lead += (
            "\n\nReturns ONE page. `Page::$total` is the server's count across all pages "
            "and is not `count($page)` — see §27.4 rule 4."
        )
    elif kind == "array":
        lead += (
            "\n\nReturns the server's complete list. This endpoint is NOT paginated, so "
            "the result is a plain list and never a `Page` (§27.4 rule 4)."
        )
    elif kind == "none":
        lead += "\n\nReturns nothing; the server answers with an empty body."

    if op["method"] == "DELETE":
        lead += (
            "\n\nNOT idempotent (§27.4 rule 6): deleting something already deleted raises "
            "{@see \\Axiam\\Sdk\\Management\\NotFoundError} rather than succeeding quietly."
        )
    if op["sensitive_response_fields"]:
        fields = ", ".join(f"`{f}`" for f in op["sensitive_response_fields"])
        lead += (
            f"\n\nThe response carries a ONE-TIME secret ({fields}): the server will not "
            "return it again, so a caller that does not persist it here cannot recover it "
            "(§27.5)."
        )
    return lead


def emit_operation(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """One generated method on a namespace handle."""
    params = operation_params(namespace, op)
    decl_ret, doc_ret = response_php(op)
    name = method(opname)
    canonical = f"{namespace}.{opname}"

    tags = [f"@param {p['doc']} ${p['name']} {p['text']}" for p in params]
    if doc_ret != "void":
        tags.append(f"@return {doc_ret}")
    out = docblock(operation_doc(op, name), "    ", tags)

    if params:
        out.append(f"    public function {name}(")
        for p in params:
            default = "" if p["required"] else " = null"
            out.append(f"        {p['decl']} ${p['name']}{default},")
        out.append(f"    ): {decl_ret} {{")
    else:
        out.append(f"    public function {name}(): {decl_ret}")
        out.append("    {")

    implicit = implicit_params(namespace, op)
    path_values = []
    for pname in path_param_names(op):
        if pname == "org_id" and pname in implicit:
            path_values.append(f"'{pname}' => $this->orgId()")
        elif pname == "tenant_id" and pname in implicit:
            path_values.append(f"'{pname}' => $this->tenantId()")
        else:
            path_values.append(f"'{pname}' => ${camel(pname)}")
    pv = "[" + ", ".join(path_values) + "]" if path_values else "[]"

    query_entries = [f"'{p['wire']}' => ${p['name']}" for p in params if p["kind"] == "query"]
    qv = "[" + ", ".join(query_entries) + "]" if query_entries else "[]"

    body_param = next((p for p in params if p["kind"] == "body"), None)

    if op["response"]["kind"] == "page":
        model = pascal(op["response"]["schema"].lstrip("[]"))
        out.append(f"        return $this->transport->sendPage(")
        out.append(f"            '{canonical}',")
        out.append(f"            '{op['path']}',")
        out.append(f"            {pv},")
        out.append(f"            {qv},")
        out.append("            $page ?? new PageRequest(),")
        out.append(f"            static fn (array $item): {model} => {model}::fromArray($item),")
        out.append("        );")
        out.append("    }")
        return out

    call = [
        f"        $decoded = $this->transport->send(",
        f"            '{canonical}',",
        f"            '{op['method']}',",
        f"            '{op['path']}',",
        f"            {pv},",
        f"            {qv},",
    ]
    call.append(f"            ${body_param['name']}->toArray()," if body_param else "            null,")
    call.append("        );")

    if op["response"]["kind"] == "none":
        # The 36 no-content operations still go through send(); the decoded value is
        # simply discarded. Routing them past the transport instead would put them on a
        # different request path, which is exactly what §27.8 forbids.
        out.extend(line.replace("$decoded = ", "", 1) if "$decoded = " in line else line
                   for line in call)
        out.append("    }")
        return out

    out.extend(call)
    out.append("")
    model = pascal(op["response"]["schema"].lstrip("[]"))
    if op["response"]["kind"] == "array":
        out.append("        $items = [];")
        out.append("        foreach ($decoded ?? [] as $item) {")
        out.append("            if (is_array($item)) {")
        out.append(f"                $items[] = {model}::fromArray($item);")
        out.append("            }")
        out.append("        }")
        out.append("")
        out.append("        return $items;")
    else:
        out.append(f"        return {model}::fromArray($decoded ?? []);")
    out.append("    }")
    return out


def emit_namespace(namespace: str, nsdef: dict[str, Any]) -> str:
    """One namespace handle class (§27.2)."""
    cls = f"{pascal(namespace)}Api"
    # Both names, for a union: the code calls the DISPATCHER (`X::fromArray`) while the
    # signature declares the INTERFACE (`XVariant`). Importing only one leaves the other
    # resolving against this namespace, where it does not exist.
    uses: list[str] = []
    for op in nsdef["operations"].values():
        for schema in (op["response"]["schema"], op["request_schema"]):
            if not schema:
                continue
            bare = pascal(schema.lstrip("[]"))
            uses.append(f"{MODELS_NS}\\{bare}")
            if bare in UNIONS:
                uses.append(f"{MODELS_NS}\\{bare}Variant")

    out = [header(API_NS, uses)]
    out.extend(docblock(
        escape(nsdef["doc"]) +
        f"\n\nThe `{namespace}` namespace handle (CONTRACT.md §27.2), reached as "
        f"`$client->management()->{method(namespace)}()`. Every method here goes through the "
        "one shared {@see ManagementTransport}, so §3 CSRF, the §4 cookie jar, the §5 tenant "
        "header, §6 TLS, §16 retry and §19 telemetry apply without this class doing anything "
        "to opt in (§27.8)."
    ))
    out.append(f"final class {cls} extends ManagementSupport")
    out.append("{")
    bodies = []
    for opname, op in nsdef["operations"].items():
        bodies.append("\n".join(emit_operation(namespace, opname, op)))
    out.append("\n\n".join(bodies))
    out.append("}")
    return "\n".join(out) + "\n"


