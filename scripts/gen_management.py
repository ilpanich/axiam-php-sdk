def example_json(schema: Any, depth: int = 0) -> Any:
    """A plausible wire value for ``schema`` — what a mounted fake server returns."""
    if depth > 6 or not isinstance(schema, dict):
        return None
    if "$ref" in schema:
        return example_for(schema["$ref"].split("/")[-1], depth + 1)
    inner = nullable_ref(schema)
    if inner:
        return example_for(inner, depth + 1)
    if isinstance(schema.get("allOf"), list) and len(schema["allOf"]) == 1:
        return example_json(schema["allOf"][0], depth)
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return schema["enum"][0]
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)
    if kind == "array":
        return [example_json(schema.get("items") or {}, depth + 1)]
    if kind == "integer":
        return 1
    if kind == "number":
        return 1.5
    if kind == "boolean":
        return True
    if kind == "string":
        fmt = schema.get("format")
        if fmt == "uuid":
            return EXAMPLE_UUID
        if fmt == "date-time":
            return EXAMPLE_TIME
        return "example"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        return {k: example_json(v, depth + 1) for k, v in (schema.get("properties") or {}).items()}
    return None


def example_for(name: str, depth: int = 0) -> Any:
    """A plausible wire object for the named schema."""
    if depth > 6:
        return None
    schema = SCHEMAS.get(name) or {}
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return schema["enum"][0]
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        resolved = resolve_ref(payload) if "$ref" in payload else payload
        out = {tag: value}
        for key, sub in (resolved.get("properties") or {}).items():
            out[key] = example_json(sub, depth + 1)
        return out
    props, _, _ = flatten(name)
    return {k: example_json(v, depth + 1) for k, v in props.items()}


def php_literal(value: Any, indent: str = "") -> str:
    """Render a Python value as a PHP literal (used for mounted response bodies)."""
    pad = indent + "    "
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace("'", "\\'")
        return f"'{escaped}'"
    if isinstance(value, list):
        if not value:
            return "[]"
        items = ",\n".join(f"{pad}{php_literal(v, pad)}" for v in value)
        return "[\n" + items + f",\n{indent}]"
    if isinstance(value, dict):
        if not value:
            return "[]"
        items = ",\n".join(
            f"{pad}'{k}' => {php_literal(v, pad)}" for k, v in value.items())
        return "[\n" + items + f",\n{indent}]"
    return "null"


def example_response(op: dict[str, Any]) -> Any:
    """The body a fake server returns for one operation, honouring `response.kind`.

    Reads ``response.kind`` and NEVER infers plurality from the schema NAME. The
    registry's ``response.schema`` carries no ``[]`` prefix, so a generator that guessed
    from the name typed all 13 bare-array reads as single objects — the exact bug the
    Kotlin port shipped and had to fix.
    """
    kind = op["response"]["kind"]
    schema = op["response"]["schema"]
    if kind == "none" or not schema:
        return None
    body = example_for(schema.lstrip("[]"))
    if kind == "page":
        return {"items": [body], "total": 1, "offset": 0, "limit": 50}
    if kind == "array":
        return [body]
    return body


def php_value_literal(schema: Any, secret: bool, depth: int = 0) -> str:
    """A PHP expression constructing one field's value, for a request-body fixture."""
    if secret:
        return "new \\Axiam\\Sdk\\Core\\Sensitive('s3cret')"
    if depth > 5 or not isinstance(schema, dict):
        return "null"
    if "$ref" in schema:
        return model_literal(schema["$ref"].split("/")[-1], depth + 1)
    inner = nullable_ref(schema)
    if inner:
        return model_literal(inner, depth + 1)
    if isinstance(schema.get("allOf"), list) and len(schema["allOf"]) == 1:
        return php_value_literal(schema["allOf"][0], False, depth)
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return "'" + str(schema["enum"][0]) + "'"
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)
    if kind == "array":
        return "[" + php_value_literal(schema.get("items") or {}, False, depth + 1) + "]"
    if kind == "integer":
        return "1"
    if kind == "number":
        return "1.5"
    if kind == "boolean":
        return "true"
    if kind == "string":
        fmt = schema.get("format")
        if fmt == "uuid":
            return f"'{EXAMPLE_UUID}'"
        if fmt == "date-time":
            return f"'{EXAMPLE_TIME}'"
        return "'example'"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        return "[]"
    # An untyped/free-form schema (`metadata: {}`) still needs a value a caller could
    # pass. `null` is the one thing it must NOT be: on a sparse body null means "omit",
    # so a fixture built from null cannot demonstrate that naming a field sends it.
    return "[]"


def model_literal(name: str, depth: int = 0) -> str:
    """A PHP expression constructing one model, for a request-body fixture."""
    if depth > 5:
        return "null"
    rendered = pascal(name)
    schema = SCHEMAS.get(name) or {}
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return f"Models\\{rendered}::{enum_case(str(schema['enum'][0]))}"
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        arm = f"{rendered}{pascal(value)}"
        resolved = resolve_ref(payload) if "$ref" in payload else payload
        props = resolved.get("properties") or {}
        required = set(resolved.get("required") or [])
        args = [php_value_literal(s, False, depth + 1) for k, s in props.items() if k in required]
        return f"new Models\\{arm}(" + ", ".join(args) + ")"

    secrets = sensitive_map().get(name, set())
    fields, _ = field_list(name, secrets)
    args = [php_value_literal(f["schema"], f["secret"], depth + 1)
            for f in fields if f["required"]]
    return f"new Models\\{rendered}(" + ", ".join(args) + ")"


def call_arguments(namespace: str, op: dict[str, Any]) -> list[str]:
    """The arguments a generated test passes to one operation."""
    args = []
    for p in operation_params(namespace, op):
        if p["kind"] == "path":
            args.append(f"'{EXAMPLE_UUID}'")
        elif p["kind"] == "body":
            args.append(model_literal(op["request_schema"].lstrip("[]")))
        elif p["kind"] == "page":
            continue
        elif p["required"]:
            t = p["decl"]
            args.append({"int": "1", "float": "1.5", "bool": "true"}.get(t, "'example'"))
    return args


def expected_path(op: dict[str, Any]) -> str:
    """The concrete path a generated test expects on the wire."""
    return re.sub(r"\{[^}]+\}", EXAMPLE_UUID, op["path"])


def emit_surface_test() -> str:
    """One conformance case per operation: right method, right path, nothing dropped."""
    out = [BANNER + "\nnamespace Axiam\\Sdk\\Tests\\Management;\n"]
    out.append("use Axiam\\Sdk\\Management\\Models;")
    out.append("use Axiam\\Sdk\\Management\\Page;")
    out.append("")
    out.extend(docblock(
        "One case per CONTRACT.md §27 operation — all 146 of them.\n\n"
        "Each asserts three things about one operation: it issues the METHOD the registry "
        "names, against the PATH the registry names, and — where the operation returns a "
        "body — that every field `openapi.json` declares survives the decode. The third is "
        "the one that earns its keep: the first two pass even when a generator silently "
        "drops a field.\n\n"
        "Generated by `scripts/gen_management.py`; CI re-runs it with `--check`."
    ))
    out.append("final class ManagementSurfaceGeneratedTest extends ManagementTestCase")
    out.append("{")

    cases = []
    count = 0
    for namespace, nsdef in REGISTRY["namespaces"].items():
        for opname, op in nsdef["operations"].items():
            count += 1
            body = example_response(op)
            args = call_arguments(namespace, op)
            call = f"$client->management()->{method(namespace)}()->{method(opname)}(" + ", ".join(args) + ")"
            test_name = "test" + pascal(namespace) + pascal(opname) + "ReachesItsRoute"

            block = inline_doc(
                f"`{op['method']} {op['path']}` — the `{namespace}.{opname}` operation.", "    ")
            block.append(f"    public function {test_name}(): void")
            block.append("    {")
            if body is None:
                block.append("        $client = $this->signedInClient(204, null);")
                block.append(f"        {call};")
            else:
                block.append("        $mounted = " + php_literal(body, "        ") + ";")
                block.append("        $client = $this->signedInClient(200, $mounted);")
                block.append(f"        $result = {call};")
            block.append("")
            block.append("        $request = $this->lastRequest();")
            block.append(f"        self::assertSame('{op['method']}', $request->getMethod());")
            block.append(f"        self::assertSame('{expected_path(op)}', $request->getUri()->getPath());")

            kind = op["response"]["kind"]
            if kind == "page":
                block.append("        self::assertInstanceOf(Page::class, $result);")
                block.append("        self::assertSame(1, $result->total);")
                block.append("        self::assertCount(1, $result->items);")
                block.append("        $this->assertDecodedEveryField($mounted['items'][0], $result->items[0]);")
            elif kind == "array":
                block.append("        self::assertIsArray($result);")
                block.append("        self::assertCount(1, $result);")
                block.append("        $this->assertDecodedEveryField($mounted[0], $result[0]);")
            elif kind == "object":
                block.append("        $this->assertDecodedEveryField($mounted, $result);")
            block.append("    }")
            cases.append("\n".join(block))

    # §27.9: the count itself is an assertion, so an operation silently dropped from the
    # registry fails the build rather than quietly reducing coverage.
    tail = docblock(
        "§27.9: all 146 registry operations are covered by a case above.\n\n"
        "Counted reflectively rather than written as a literal on both sides — "
        "`assertSame(146, 146)` is a tautology, and a case removed by a bad regeneration "
        "would still pass it.",
        "    ",
    )
    tail.append("    public function testEveryRegistryOperationHasACase(): void")
    tail.append("    {")
    tail.append("        $reflection = new \\ReflectionClass(self::class);")
    tail.append("        $cases = array_filter(")
    tail.append("            $reflection->getMethods(\\ReflectionMethod::IS_PUBLIC),")
    tail.append("            static fn (\\ReflectionMethod $m): bool => str_ends_with($m->getName(), 'ReachesItsRoute'),")
    tail.append("        );")
    tail.append("")
    tail.append(f"        self::assertCount({count}, $cases);")
    tail.append("    }")
    cases.append("\n".join(tail))

    out.append("\n\n".join(cases))
    out.append("}")
    return "\n".join(out) + "\n"


def sparse_models() -> list[tuple[str, list[dict[str, Any]]]]:
    """Every request schema whose fields are all optional — the sparse bodies."""
    secrets = sensitive_map()
    replacements = replacement_schemas()
    seen: set[str] = set()
    out: list[tuple[str, list[dict[str, Any]]]] = []
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            name = op["request_schema"]
            if not name:
                continue
            name = name.lstrip("[]")
            if name in seen or name in replacements:
                continue
            seen.add(name)
            fields, _ = field_list(name, secrets.get(name, set()))
            if fields and all(not f["required"] for f in fields):
                out.append((pascal(name), fields))
    return out


def emit_sparse_test() -> str:
    """One case per sparse body: naming ONE field sends exactly that field."""
    out = [BANNER + "\nnamespace Axiam\\Sdk\\Tests\\Management;\n"]
    out.append("use Axiam\\Sdk\\Management\\Models;")
    out.append("")
    out.extend(docblock(
        "One case per SPARSE §27 request body (CONTRACT.md §27.4 rule 5).\n\n"
        "Each names exactly ONE field and asserts the rendered body contains that key and "
        "no other. That is the whole of rule 5: an unset field is ABSENT, not null. The "
        "distinction is not cosmetic — on a sparse update `null` means \"erase this\" and "
        "absence means \"leave it alone\", so a serializer that emits nulls for unset "
        "fields silently wipes every field the caller did not mention.\n\n"
        "Generated by `scripts/gen_management.py`; CI re-runs it with `--check`."
    ))
    out.append("final class ManagementSparseBodiesGeneratedTest extends ManagementTestCase")
    out.append("{")

    cases = []
    for name, fields in sparse_models():
        # Not simply fields[0]: the demonstration only works with a NON-null value,
        # because on a sparse body null is precisely what "omit this" looks like.
        chosen = next(
            (f for f in fields
             if php_value_literal(f["schema"], f["secret"]) != "null"),
            fields[0],
        )
        literal = php_value_literal(chosen["schema"], chosen["secret"])
        block = inline_doc(
            f"`{name}`: naming only `{chosen['wire']}` sends only `{chosen['wire']}`.", "    ")
        block.append(f"    public function test{name}OmitsWhatYouDidNotName(): void")
        block.append("    {")
        block.append(f"        $body = new Models\\{name}({chosen['name']}: {literal});")
        block.append("")
        block.append("        $rendered = $body->toArray();")
        block.append("")
        block.append(f"        self::assertSame(['{chosen['wire']}'], array_keys($rendered));")
        block.append("    }")
        cases.append("\n".join(block))

    tail = docblock(
        "Every sparse body renders empty when nothing is named.\n\n"
        "The degenerate case of rule 5, and the one a serializer with the wrong default "
        "gets wrong most visibly: a no-op update must send `{}`, not a body that nulls out "
        "every field on the object.",
        "    ",
    )
    tail.append("    public function testAnEmptySparseBodyRendersEmpty(): void")
    tail.append("    {")
    for name, _ in sparse_models():
        tail.append(f"        self::assertSame([], (new Models\\{name}())->toArray());")
    tail.append("    }")
    cases.append("\n".join(tail))

    out.append("\n\n".join(cases))
    out.append("}")
    return "\n".join(out) + "\n"


