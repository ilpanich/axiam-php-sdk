def build() -> dict[Path, str]:
    """Every file this generator owns, keyed by absolute path."""
    files: dict[str, str] = {}
    files.update(emit_models())
    for namespace, nsdef in REGISTRY["namespaces"].items():
        files[f"{API_DIR}/{pascal(namespace)}Api.php"] = emit_namespace(namespace, nsdef)
    files[f"{API_DIR}/ManagementApi.php"] = emit_api()
    files[f"{TEST_DIR}/ManagementSurfaceGeneratedTest.php"] = emit_surface_test()
    files[f"{TEST_DIR}/ManagementSparseBodiesGeneratedTest.php"] = emit_sparse_test()
    return {ROOT / path: text for path, text in files.items()}


def prune(files: dict[Path, str]) -> list[Path]:
    """Committed generated files this run did NOT produce — i.e. now stale.

    Only ever considers the models directory, whose entire contents this generator owns.
    A schema removed from the spec must take its model file with it, or `--check` passes
    on a tree that still ships a type the contract no longer has.
    """
    stale = []
    models = ROOT / MODELS_DIR
    if models.is_dir():
        hand_written = {models / "ModelDecode.php"}
        for path in sorted(models.glob("*.php")):
            if path not in files and path not in hand_written:
                stale.append(path)
    return stale


def main() -> int:
    """Write (or, with ``--check``, verify) the generated §27 surface."""
    check = "--check" in sys.argv
    files = build()
    stale = prune(files)

    if check:
        drifted = [p for p, text in sorted(files.items())
                   if not p.exists() or p.read_text() != text]
        if drifted or stale:
            for path in drifted:
                print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            for path in stale:
                print(f"stale (no longer generated): {path.relative_to(ROOT)}", file=sys.stderr)
            print(
                "\nThe committed §27 surface disagrees with management-registry.json / "
                "openapi.json.\nRegenerate with `python3 scripts/gen_management.py` and "
                "commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"§27 surface is current ({len(files)} files).")
        return 0

    for path in stale:
        path.unlink()
        print(f"removed stale {path.relative_to(ROOT)}")

    for path, text in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
