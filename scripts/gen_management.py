#!/usr/bin/env python3
"""Generate the CONTRACT §27 management surface for the PHP SDK.

Reads ``management-registry.json`` (the 146 operations across 24 namespaces,
maintained in ``ilpanich/axiam`` and vendored here) plus ``openapi.json`` for the
schemas those operations carry, and writes:

- ``src/Management/Models/*.php`` — one ``final class``, ``enum`` or polymorphic base
  per request and response type, one class per file so PSR-4 can autoload it;
- ``src/Management/<Namespace>Api.php`` — one namespace handle per namespace (§27.2);
- ``src/Management/ManagementApi.php`` — the 24 accessors;
- ``tests/Management/ManagementSurfaceGeneratedTest.php``
- ``tests/Management/ManagementSparseBodiesGeneratedTest.php``
  — one conformance case per operation, plus the §27.9 assertion that all 146 are
  reached.

Run with ``--check`` to verify the committed output is current; that is what CI runs,
so a registry change that is not regenerated fails the build rather than shipping a
surface that disagrees with the contract.

Everything this emits must satisfy two gates this repo runs and most siblings do not:
``tools/docblock-coverage.php`` requires a docblock on EVERY public class and method
under ``src/``, and PHPStan runs at level 6, which wants the value type of every array
spelled out. Both are why the emitters below carry so much ``@param``/``@return``
plumbing: a generated file is held to the same bar as a hand-written one.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REGISTRY: dict[str, Any] = json.loads((ROOT / "management-registry.json").read_text())
SPEC: dict[str, Any] = json.loads((ROOT / "openapi.json").read_text())
SCHEMAS: dict[str, Any] = SPEC["components"]["schemas"]

BANNER = """<?php

declare(strict_types=1);

// Generated by scripts/gen_management.py from management-registry.json and openapi.json.
// DO NOT EDIT -- your changes will be overwritten. Regenerate with
// `python3 scripts/gen_management.py`; CI verifies the committed output is current.
"""

